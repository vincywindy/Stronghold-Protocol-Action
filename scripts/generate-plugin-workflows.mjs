import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { readCatalog, displayName } from './plugin-catalog.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
export function generatedFiles(catalog = readCatalog(), workflow = fs.readFileSync(path.join(root, '.github/workflows/docker.yml'), 'utf8')) {
  const result = new Map();
  const quote = value => `'${value.replaceAll("'", "''")}'`;
  const begin = '      # BEGIN GENERATED PLUGIN INPUTS';
  const end = '      # END GENERATED PLUGIN INPUTS';
  workflow = workflow.replaceAll('\r\n', '\n');
  if (workflow.split(begin).length !== 2 || workflow.split(end).length !== 2 || workflow.indexOf(begin) >= workflow.indexOf(end)) throw new Error('Missing or duplicate generated plugin input markers');
  // GitHub caps dispatch forms at 25 inputs: three build settings plus one checkbox per repository.
  if (3 + Object.keys(catalog.sources).length > 25) throw new Error('Repository selectors exceed GitHub limit of 25 inputs');
  const inputs = [begin, '      # Generated by scripts/generate-plugin-workflows.mjs from plugins/catalog.json.'];
  for (const [source, info] of Object.entries(catalog.sources)) {
    inputs.push(`      plugins_${source}:`, `        description: ${quote(`${info.repository.split('/')[1]}（启用管理来源；构建时不安装插件）`)}`, '        type: boolean', '        default: false');
  }
  inputs.push(end);
  result.set('.github/workflows/docker.yml', workflow.slice(0, workflow.indexOf(begin)) + inputs.join('\n') + workflow.slice(workflow.indexOf(end) + end.length));
  const lines = ['# 插件目录', '', '由 `plugins/catalog.json` 生成。所有检索到的条目均可选择，不按兼容性筛选。名称使用「仓库名 + 插件名」。', '',
    '构建时勾选仓库只启用管理来源，不安装其中的插件。启动后打开管理网页，在列表中选择需要的插件，再点击“应用选择”；支持跨仓库组合、更新和卸载。', '',
    '表中版本是构建目录快照。管理网页的“刷新目录”会重新检索来源 ref，下载固定到这次检索的完整提交 SHA；不按兼容性隐藏条目。安装结果和诊断保存在持久化卷中。', '',
    '安装与房间启用分开。Forge 导入失败时保留原包及诊断；Lele/native 复制到游戏插件目录，但不注入宿主补丁。脚本默认按 sandbox 运行，trusted 插件不会自动获得信任。', '',
    '| 选择键 | 显示名称 | 快照版本 | 接入方式 |', '| --- | --- | --- | --- |'];
  for (const p of catalog.plugins) lines.push(`| \`${p.source}/${p.id}\` | ${displayName(p, catalog)} | ${p.version} | ${p.adapter} |`);
  lines.push('', '## 跟踪来源', '');
  for (const [key, source] of Object.entries(catalog.sources)) lines.push(`- ${key}: [${source.repository}](https://github.com/${source.repository})，ref: \`${source.ref}\`；[目录检索快照](https://github.com/${source.repository}/tree/${source.revision})。`);
  lines.push('', '维护目录快照：`node scripts/refresh-plugin-catalog.mjs`，再运行 `node scripts/generate-plugin-workflows.mjs`。新增来源需要重新构建镜像；已有来源新增插件可直接在管理网页刷新目录获取。', '');
  result.set('plugins/README.md', lines.join('\n'));
  return result;
}
export function generate(check = false) {
  const files = generatedFiles();
  for (const name of fs.readdirSync(path.join(root, '.github/workflows')).filter(n => /^plugins-.*-\d+\.yml$/.test(n))) {
    if (!files.has(`.github/workflows/${name}`)) throw new Error(`Remove obsolete generated workflow: ${name}`);
  }
  for (const [name, content] of files) {
    const file = path.join(root, name);
    if (check) {
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8').replaceAll('\r\n', '\n') !== content) throw new Error(`Outdated generated file: ${name}`);
    } else fs.writeFileSync(file, content);
  }
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) generate(process.argv.includes('--check'));
