import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { readCatalog, displayName } from './plugin-catalog.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
export function generatedFiles(catalog = readCatalog()) {
  const result = new Map();
  for (const [source, info] of Object.entries(catalog.sources)) {
    const plugins = catalog.plugins.filter(p => p.source === source);
    // GitHub permits 25 dispatch inputs: four common fields leave 21 boolean checkboxes per page.
    for (let offset = 0; offset < plugins.length; offset += 21) {
      const page = plugins.slice(offset, offset + 21), number = offset / 21 + 1;
      const lines = [
        '# Generated by node scripts/generate-plugin-workflows.mjs; edit plugins/catalog.json instead.',
        `name: 'Plugins - ${info.repository.split('/')[1]} (${number})'`, '', 'on:', '  workflow_dispatch:', '    inputs:',
        '      upstream_ref:', "        description: 'Game release, branch, tag or SHA; latest follows the latest stable release'", '        type: string', "        default: 'latest'",
        '      include_assets:', "        description: 'Include game art/audio and plugin art'", '        type: boolean', '        default: true',
        '      image_tag:', "        description: 'Custom image tag; required when any plugin is selected; never latest'", '        type: string', "        default: ''",
        '      additional_plugins:', "        description: 'Optional comma-separated keys from another page/repository, e.g. forge/theme-night'", '        type: string', "        default: ''",
      ];
      for (const p of page) lines.push(`      p_${p.id.replaceAll('-', '_')}:`, `        description: '${displayName(p, catalog).replaceAll("'", "''")}'`, '        type: boolean', '        default: false');
      lines.push('', 'permissions:', '  contents: read', '  packages: write', '', 'jobs:', '  build:', '    uses: ./.github/workflows/docker.yml', '    with:',
        '      upstream_ref: ${{ inputs.upstream_ref }}', '      include_assets: ${{ inputs.include_assets }}', '      image_tag: ${{ inputs.image_tag }}', '      plugins: >-');
      for (const p of page) lines.push(`        \${{ inputs.p_${p.id.replaceAll('-', '_')} && '${source}/${p.id},' || '' }}`);
      lines.push('        ${{ inputs.additional_plugins }}', '    secrets: inherit', '');
      result.set(`.github/workflows/plugins-${source}-${number}.yml`, lines.join('\n'));
    }
  }
  const lines = ['# 插件目录', '', '由 `plugins/catalog.json` 生成。所有检索到的条目均可勾选，不按兼容性筛选。名称使用「仓库名 + 插件名」。', '',
    '表中版本是检索快照；手动构建会获取来源 ref 的最新提交，并从该提交获取所选包的最新版本。实际版本和完整 SHA 见镜像 `/app/plugin-build.json`。', '',
    '未勾选不添加；安装成功后仍需房主/玩家在游戏中开启。导入失败或仅部分导入不会阻止打包，原包始终保存在 `/app/plugin-sources/`。下载失败、校验失败或游戏无法启动仍会使构建失败。', '',
    '| 选择键 | 显示名称 | 快照版本 | 接入方式 |', '| --- | --- | --- | --- |'];
  for (const p of catalog.plugins) lines.push(`| \`${p.source}/${p.id}\` | ${displayName(p, catalog)} | ${p.version} | ${p.adapter} |`);
  lines.push('', '## 跟踪来源', '');
  for (const [key, source] of Object.entries(catalog.sources)) lines.push(`- ${key}: [${source.repository}](https://github.com/${source.repository})，ref: \`${source.ref}\`；[目录检索快照](https://github.com/${source.repository}/tree/${source.revision})。`);
  lines.push('', '刷新新增插件：`node scripts/refresh-plugin-catalog.mjs`，再运行 `node scripts/generate-plugin-workflows.mjs` 并提交生成文件。GitHub 勾选框是静态配置，需要合并目录更新才会出现新条目；已有插件更新无需修改勾选框。', '');
  result.set('plugins/README.md', lines.join('\n'));
  return result;
}
export function generate(check = false) {
  const files = generatedFiles();
  for (const name of fs.readdirSync(path.join(root, '.github/workflows')).filter(n => /^plugins-.*-\d+\.yml$/.test(n))) {
    if (!files.has(`.github/workflows/${name}`)) throw new Error(`Remove obsolete generated workflow: ${name}`);
  }
  for (const [name, content] of files) {
    const file = path.join(root, name);
    if (check) {
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8').replaceAll('\r\n', '\n') !== content) throw new Error(`Outdated generated file: ${name}`);
    } else fs.writeFileSync(file, content);
  }
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) generate(process.argv.includes('--check'));
